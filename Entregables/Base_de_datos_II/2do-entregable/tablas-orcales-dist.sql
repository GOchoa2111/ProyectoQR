CREATE TABLE Historial_Auditoria (
    AuditoriaID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NombreTabla      VARCHAR2(30) NOT NULL,
    ID_Registro      VARCHAR2(100),
    TipoOperacion    VARCHAR2(10) NOT NULL,
    UsuarioBD        VARCHAR2(30) NOT NULL,
    FechaOperacion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT chk_tipo_operacion CHECK (TipoOperacion IN ('INSERT', 'UPDATE', 'DELETE'))
);
