CREATE TABLE Estudiantes (
    EstudianteID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR2(100),
    Apellido VARCHAR2(100),
    CodigoQR VARCHAR2(255) UNIQUE
);

CREATE TABLE Marcajes (
    MarcajeID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EstudianteID NUMBER,
    FechaHora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Tipo VARCHAR2(10),
    FOREIGN KEY (EstudianteID) REFERENCES Estudiantes(EstudianteID)
);


CREATE TABLE HistorialEstudiantes (
    ID_Historial NUMBER PRIMARY KEY,
    Accion VARCHAR2(20),
    Descripcion VARCHAR2(200),
    Fecha TIMESTAMP DEFAULT SYSTIMESTAMP
);

